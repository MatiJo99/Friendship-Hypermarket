/** Star that renders full, half or empty. */
export function Star({ fill = "full", className = "" }) {
  const path = "m12 17.6-5.3 3 1.4-6-4.6-4 6.1-.5L12 4.4l2.4 5.7 6.1.5-4.6 4 1.4 6z";

  if (fill === "half") {
    const id = `half-${Math.random().toString(36).slice(2, 8)}`;
    return (
      <svg viewBox="0 0 24 24" className={className} aria-hidden="true">
        <defs>
          <linearGradient id={id}>
            <stop offset="50%" stopColor="currentColor" />
            <stop offset="50%" stopColor="currentColor" stopOpacity="0.22" />
          </linearGradient>
        </defs>
        <path d={path} fill={`url(#${id})`} />
      </svg>
    );
  }

  return (
    <svg viewBox="0 0 24 24" className={className} aria-hidden="true">
      <path d={path} fill="currentColor" opacity={fill === "full" ? 1 : 0.22} />
    </svg>
  );
}
